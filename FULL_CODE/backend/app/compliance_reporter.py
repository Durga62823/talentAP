"""Regulatory compliance dossiers built from DreamGuard's own evidence: the hash-chained audit
ledger, source-integrity runs and the live policy set.

Frameworks: DPDP Act 2023 (India), RBI Cyber Security Framework for banks, PCI-DSS v4.0
Requirement 3. A dossier is canonical JSON; its SHA-256 is signed with a server Ed25519 key
(public key served at /api/compliance/reports/public-key) and the generation is recorded in the
audit chain, so a copy can be verified offline and its origin proven from the ledger.

Dossiers carry metadata and counts only - never protected values. They are automated control
evidence that supports, and does not replace, an auditor's, DPO's or QSA's assessment."""
