FRAMEWORKS = {
    "DPDP": "DPDP Act 2023 (India) - Compliance Pack",
    "RBI": "RBI Cyber Security Framework - Annexure",
    "PCI_DSS": "PCI-DSS v4.0 Requirement 3 - Card Masking Attestation",
}
PRIVILEGED_ROLES = {"admin"}  # the role documented as having a business need for full PAN
TEST_PAN = "4111111111111111"  # published test card number: shows the egress rendering per role
ADMIN_ACTIONS = {
    "policy_change", "user_create", "user_update", "grant_change", "connection_create", "connection_delete",
    "classification_change", "demo_reset", "data_import", "upload_delete", "scim_token_create",
    "scim_token_revoke", "scim_user_create", "scim_user_update",
}
WRITE_REJECTIONS = {"not_select", "multiple_statements"}
DISCLAIMER = ("Automated control evidence generated by DreamGuard from its audit ledger, policy set and integrity runs. "
              "It supports, and does not replace, assessment by an auditor, Data Protection Officer or PCI QSA.")


# ---- evidence collection (one pass over the ledger) ---------------------------------------

@dataclass
class Evidence:
    events: int = 0
    first_ts: str | None = None
    last_ts: str | None = None
    head_seq: int | None = None
    head_hash: str | None = None
    by_action: Counter = field(default_factory=Counter)
    failed: Counter = field(default_factory=Counter)
    recent_failed: list[dict] = field(default_factory=list)
    admin_actions: list[dict] = field(default_factory=list)
    break_glass: list[dict] = field(default_factory=list)  # most recent 100
    break_glass_count: int = 0
    purposes: Counter = field(default_factory=Counter)
    purpose_by_role: dict[str, Counter] = field(default_factory=lambda: defaultdict(Counter))
    purpose_grants: list[dict] = field(default_factory=list)  # most recent 50
    purpose_grant_count: int = 0
    table_reads: dict[str, Counter] = field(default_factory=lambda: defaultdict(Counter))
    rows_by_role: Counter = field(default_factory=Counter)
    write_attempts_blocked: int = 0
    pan_egress: dict[str, Counter] = field(default_factory=lambda: defaultdict(Counter))
    pan_cleartext: list[dict] = field(default_factory=list)  # first 50
    pan_cleartext_count: int = 0
    dossiers: list[dict] = field(default_factory=list)


def pan_sources(db: Session) -> set[tuple[str, str]]:
    return {(c.connection_id, f"{c.table_name}.{c.column_name}".lower())
            for c in db.scalars(select(Classification).where(Classification.category == "CREDIT_CARD"))}


def _cleartext(d: dict) -> bool:
    # COUNT, and SUM/AVG under AGGREGATE_ONLY, are released as ALLOW without exposing a PAN.
    return d.get("action") == "ALLOW" and d.get("aggregate") in (None, "MIN", "MAX")


def collect(db: Session) -> Evidence:
    ev = Evidence()
    pans = pan_sources(db)
    for e in db.scalars(select(AuditEvent).order_by(AuditEvent.seq)):
        ev.events += 1
        ts = iso(e.ts)
        ev.first_ts = ev.first_ts or ts
        ev.last_ts, ev.head_seq, ev.head_hash = ts, e.seq, e.entry_hash
        ev.by_action[e.action] += 1
        d = e.details or {}
        ctx = d.get("access_context") or {}
        ref = {"seq": e.seq, "ts": ts, "actor": e.actor_name, "role": e.role, "action": e.action}
        if e.outcome != "success":
            ev.failed[e.action] += 1
            ev.recent_failed = (ev.recent_failed + [ref | {"outcome": e.outcome, "reason": (e.reason or "")[:120]}])[-25:]
        if e.action in ADMIN_ACTIONS:
            target = next((f"{k}={d[k]}" for k in ("policy_id", "username", "role", "token_id", "change") if d.get(k) is not None), "")
            ev.admin_actions = (ev.admin_actions + [ref | {"outcome": e.outcome, "target": str(target)[:80]}])[-50:]
        if e.action == "compliance_report_generate":
            ev.dossiers = (ev.dossiers + [ref | {"framework": d.get("framework"), "dossier_sha256": d.get("dossier_sha256")}])[-10:]
        if e.action == "query_denied" and d.get("code") in WRITE_REJECTIONS:
            ev.write_attempts_blocked += 1
        if e.action != "query_execute":
            continue
        role = e.role or "unknown"
        purpose = ctx.get("purpose") or "UNSPECIFIED"
        ev.purposes[purpose] += 1
        ev.purpose_by_role[role][purpose] += 1
        ev.rows_by_role[role] += int(d.get("row_count") or 0)
        for t in e.tables or []:
            ev.table_reads[t][role] += 1
        if d.get("abac_granted_columns"):
            ev.purpose_grant_count += 1
            ev.purpose_grants = (ev.purpose_grants + [ref | {"purpose": ctx.get("purpose"), "ticket_id": ctx.get("ticket_id"),
                                                            "columns": d["abac_granted_columns"]}])[-50:]
        if d.get("break_glass"):
            ev.break_glass_count += 1
            ev.break_glass = (ev.break_glass + [ref | {"columns": (e.reason or "").removeprefix("break-glass raw access: "),
                                                       "justification": (d.get("justification") or "")[:160]}])[-100:]
        for dec in d.get("decisions") or []:
            src = (dec.get("source") or "").lower()
            if (e.connection_id, src) not in pans:
                continue
            clear = _cleartext(dec)
            ev.pan_egress[role]["cleartext" if clear else "masked"] += 1
            if clear and role not in PRIVILEGED_ROLES:
                ev.pan_cleartext_count += 1
                if len(ev.pan_cleartext) < 50:
                    ev.pan_cleartext.append(ref | {"source": dec.get("source"), "policy_id": dec.get("policy_id")})
    return ev


def ledger_section(db: Session, ev: Evidence) -> dict[str, Any]:
    chain = audit.verify_chain(db)
    return {"events": ev.events, "first_event": ev.first_ts, "last_event": ev.last_ts, "head_seq": ev.head_seq,
            "head_entry_hash": ev.head_hash, "chain_valid": chain["valid"], "events_recomputed": chain["checked"],
            "broken_at_seq": chain["broken_at_seq"], "algorithm": "SHA-256 hash chain (prev_hash -> entry_hash)"}


def integrity_section(db: Session) -> dict[str, Any]:
    names = {c.id: c.name for c in db.scalars(select(DbConnection))}
    runs = list(db.scalars(select(IntegrityRun).order_by(IntegrityRun.created_at.desc())))
    return {
        "runs": len(runs),
        "all_match": all(r.match for r in runs) if runs else None,
        "mismatches": sum(not r.match for r in runs),
        "recent": [{"at": iso(r.created_at), "connection": names.get(r.connection_id, "(removed)"), "tables": len(r.tables),
                    "rows_covered": r.rows_covered, "before": r.before_fingerprint, "after": r.after_fingerprint, "match": r.match}
                   for r in runs[:10]],
    }


def pci_analysis(db: Session) -> dict[str, Any]:
    """Worst-case policy analysis per PAN column and role: every ABAC grant is assumed reachable,
    and break-glass counts as raw for roles holding raw:break_glass."""
    roles = {r.name: set(r.permissions or []) for r in db.scalars(select(Role))}
    grants = {(g.connection_id, g.table_name.lower(), g.role) for g in db.scalars(select(TableGrant))}
    names = {c.id: c.name for c in db.scalars(select(DbConnection))}
    resolvers: dict[tuple[str, str], PolicyResolver] = {}
    columns, reachable = [], []
    for c in db.scalars(select(Classification).where(Classification.category == "CREDIT_CARD").order_by(Classification.table_name, Classification.id)):
        per_role = {}
        for role, perms in sorted(roles.items()):
            if (c.connection_id, c.table_name.lower(), role) not in grants:
                per_role[role] = {"access": "no table grant"}
                continue
            key = (role, c.connection_id)
            if key not in resolvers:
                resolvers[key] = PolicyResolver(db, role, c.connection_id, assume_conditions_met=True)
            d = resolvers[key].decide(c.schema_name, c.table_name, c.column_name)
            raw = d.action == "ALLOW" or ("break-glass not invoked" in d.reason and "raw:break_glass" in perms)
            per_role[role] = {"worst_case_action": d.action, "egress_example": "(query rejected)" if d.action == "DENY"
                              else masking.apply(d.action, TEST_PAN, "CREDIT_CARD"), "raw_reachable": raw, "policy_id": d.policy_id}
            if raw and role not in PRIVILEGED_ROLES:
                reachable.append({"connection": names.get(c.connection_id), "column": f"{c.table_name}.{c.column_name}", "role": role,
                                  "policy_id": d.policy_id})
        columns.append({"connection": names.get(c.connection_id, "(removed)"), "column": f"{c.table_name}.{c.column_name}", "roles": per_role})
    return {"pan_columns": columns, "non_privileged_raw_reachable": reachable}


# ---- dossiers -----------------------------------------------------------------------------

def _section(sid: str, title: str, reference: str, data: dict[str, Any]) -> dict[str, Any]:
    return {"id": sid, "title": title, "reference": reference, "data": data}


def section_data(dossier: dict[str, Any], sid: str) -> dict[str, Any]:
    return next(s["data"] for s in dossier["sections"] if s["id"] == sid)


def build_dossier(db: Session, framework: str, principal: Principal, ev: Evidence | None = None,
                  ledger: dict[str, Any] | None = None) -> dict[str, Any]:
    if framework not in FRAMEWORKS:
        raise ValueError(f"unknown framework {framework}")
    ev = ev or collect(db)
    ledger = ledger or ledger_section(db, ev)
    findings: list[str] = []
    if not ledger["chain_valid"]:
        findings.append(f"Audit hash chain broken at sequence #{ledger['broken_at_seq']}")

    if framework == "DPDP":
        integ = integrity_section(db)
        if integ["mismatches"]:
            findings.append(f"{integ['mismatches']} integrity run(s) detected source-data changes")
        sections = [
            _section("data_principal_access", "Data Principal access summary (processing of personal data)",
                     "DPDP Act 2023 s.8 (obligations of Data Fiduciary), s.11 (right to access information)", {
                         "note": "DreamGuard never logs record identifiers or values, so access is summarised per table and role.",
                         "reads_by_table": {t: dict(c) for t, c in sorted(ev.table_reads.items())},
                         "rows_disclosed_by_role": dict(ev.rows_by_role),
                     }),
            _section("purpose_distribution", "Purpose of processing", "DPDP Act 2023 s.4-s.7 (lawful purpose)", {
                "queries_by_purpose": dict(ev.purposes),
                "by_role": {r: dict(c) for r, c in sorted(ev.purpose_by_role.items())},
                "purpose_bound_elevations": ev.purpose_grants,
            }),
            _section("exceptional_access", "Consent and break-glass (exceptional access) log", "DPDP Act 2023 s.6, s.8(5)", {
                "note": "Consent artefacts are managed outside DreamGuard; exceptional raw access is listed with its justification.",
                "break_glass_total": ev.break_glass_count,
                "break_glass_events": ev.break_glass,
            }),
            _section("zero_mutation", "Zero data mutation proof", "DPDP Act 2023 s.8(3), s.8(5) (accuracy, safeguards)", {
                "integrity_runs": integ,
                "write_statements_blocked": ev.write_attempts_blocked,
                "control": "Protected reads run on read-only connections; non-SELECT statements are rejected before execution.",
            }),
        ]
    elif framework == "RBI":
        sections = [
            _section("admin_actions", "Privileged / administrator actions", "RBI CSF Annex 1 - User access control, privileged accounts", {
                "counts": {a: ev.by_action[a] for a in sorted(ADMIN_ACTIONS) if ev.by_action[a]},
                "recent": ev.admin_actions,
            }),
            _section("failed_access", "Failed access attempts", "RBI CSF Annex 1 - Audit logs, monitoring and analysis", {
                "counts": dict(ev.failed), "recent": ev.recent_failed,
            }),
            _section("break_glass", "Break-glass justifications", "RBI CSF Annex 1 - Privileged access",
                     {"total": ev.break_glass_count, "events": ev.break_glass}),
            _section("federation", "Identity federation and provisioning", "RBI CSF Annex 1 - User access control", {
                "sso_logins": ev.by_action["sso_login"], "sso_failures": ev.by_action["sso_login_failed"],
                "scim_provisioned": ev.by_action["scim_user_create"], "scim_updates": ev.by_action["scim_user_update"],
                "scim_auth_failures": ev.by_action["scim_auth_failed"],
            }),
            _section("chain_certificate", "Audit hash-chain verification certificate", "RBI CSF Annex 1 - Audit log integrity", ledger),
        ]
    else:
        pci = pci_analysis(db)
        for r in pci["non_privileged_raw_reachable"]:
            findings.append(f"Role {r['role']} can reach cleartext PAN in {r['column']} (policy #{r['policy_id']})")
        if ev.pan_cleartext_count:
            findings.append(f"{ev.pan_cleartext_count} cleartext PAN egress instance(s) to non-privileged roles in the ledger")
        sections = [
            _section("pan_policy", "PAN masking on egress (worst case, all ABAC grants assumed)", "PCI-DSS v4.0 Req 3.4.1", pci),
            _section("pan_egress_observed", "Observed PAN egress in the audit ledger", "PCI-DSS v4.0 Req 3.4.1, Req 10.2", {
                "by_role": {r: dict(c) for r, c in sorted(ev.pan_egress.items())},
                "non_privileged_cleartext_instances": ev.pan_cleartext_count,
                "instances": ev.pan_cleartext,
                "privileged_roles_with_business_need": sorted(PRIVILEGED_ROLES),
            }),
            _section("chain_certificate", "Evidence integrity", "PCI-DSS v4.0 Req 10.3 (audit logs protected)", ledger),
        ]

    conns = [{"id": c.id, "name": c.name, "kind": c.kind} for c in db.scalars(select(DbConnection).order_by(DbConnection.created_at))]
    return {
        "schema": "dreamguard.compliance-dossier/v1",
        "framework": framework,
        "title": FRAMEWORKS[framework],
        "generated_at": utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"),
        "generated_by": {"username": principal.username, "role": principal.role},
        "scope": {"connections": conns},
        "ledger": ledger,
        "status": "PASS" if not findings else "ATTENTION_REQUIRED",
        "findings": findings,
        "sections": sections,
        "disclaimer": DISCLAIMER,
    }


def summary(db: Session, principal: Principal) -> dict[str, Any]:
    ev = collect(db)
    ledger = ledger_section(db, ev)
    dossiers = {f: build_dossier(db, f, principal, ev, ledger) for f in FRAMEWORKS}
    integ = section_data(dossiers["DPDP"], "zero_mutation")["integrity_runs"]
    pci = section_data(dossiers["PCI_DSS"], "pan_policy")
    return {
        "generated_at": utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"),
        "ledger": ledger,
        "queries": {"executed": ev.by_action["query_execute"], "denied": ev.by_action["query_denied"]},
        "failed_access": sum(ev.failed.values()),
        "privilege_violations": ev.by_action["privilege_violation"],
        "break_glass": ev.break_glass_count,
        "purpose_distribution": dict(ev.purposes),
        "purpose_bound_elevations": ev.purpose_grant_count,
        "sso_logins": ev.by_action["sso_login"],
        "integrity": {"runs": integ["runs"], "all_match": integ["all_match"]},
        "pci": {"pan_columns": len(pci["pan_columns"]), "non_privileged_cleartext_egress": ev.pan_cleartext_count,
                "non_privileged_raw_reachable": len(pci["non_privileged_raw_reachable"])},
        "frameworks": [{"id": f, "title": t, "status": dossiers[f]["status"], "findings": dossiers[f]["findings"]}
                       for f, t in FRAMEWORKS.items()],
        "recent_dossiers": ev.dossiers,
    }


# ---- signing ------------------------------------------------------------------------------

def _signing_key() -> Ed25519PrivateKey:
    pem = secret_file("report_signing_ed25519.pem", lambda: Ed25519PrivateKey.generate().private_bytes(
        serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
    return serialization.load_pem_private_key(pem, None)  # type: ignore[return-value]


def public_key_info() -> dict[str, str]:
    pub = _signing_key().public_key()
    raw = pub.public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    pem = pub.public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo).decode()
    return {"algorithm": "Ed25519", "key_id": hashlib.sha256(raw).hexdigest()[:16], "public_key_pem": pem}


def canonical(dossier: dict[str, Any]) -> bytes:
    return json.dumps(dossier, sort_keys=True, separators=(",", ":"), ensure_ascii=False, default=str).encode()


def seal(dossier: dict[str, Any]) -> dict[str, str]:
    digest = hashlib.sha256(canonical(dossier)).hexdigest()
    sig = _signing_key().sign(digest.encode())
    return {"algorithm": "SHA-256 over canonical JSON, signed with Ed25519", "dossier_sha256": digest,
            "signature": base64.b64encode(sig).decode(), "key_id": public_key_info()["key_id"]}


def verify(db: Session, dossier: dict[str, Any], certificate: dict[str, Any]) -> dict[str, Any]:
    digest = hashlib.sha256(canonical(dossier)).hexdigest()
    digest_ok = digest == certificate.get("dossier_sha256")
    pub = serialization.load_pem_public_key(public_key_info()["public_key_pem"].encode())
    assert isinstance(pub, Ed25519PublicKey)
    try:
        pub.verify(base64.b64decode(certificate.get("signature", "")), digest.encode())
        sig_ok = True
    except (InvalidSignature, ValueError):
        sig_ok = False
    anchored = any((e.details or {}).get("dossier_sha256") == digest
                   for e in db.scalars(select(AuditEvent).where(AuditEvent.action == "compliance_report_generate")))
    return {"valid": digest_ok and sig_ok and anchored, "sha256_matches": digest_ok, "signature_valid": sig_ok,
            "anchored_in_audit_ledger": anchored, "recomputed_sha256": digest}


# ---- renderings ---------------------------------------------------------------------------

def _flatten(value: Any, path: str = "") -> list[tuple[str, str]]:
    if isinstance(value, dict):
        return [row for k, v in value.items() for row in _flatten(v, f"{path}.{k}" if path else str(k))] or [(path, "{}")]
    if isinstance(value, list):
        if all(not isinstance(v, (dict, list)) for v in value):
            return [(path, ", ".join(map(str, value)))]
        return [row for i, v in enumerate(value) for row in _flatten(v, f"{path}[{i}]")] or [(path, "[]")]
    return [(path, "" if value is None else str(value))]


def to_csv(dossier: dict[str, Any], cert: dict[str, Any]) -> bytes:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["section", "field", "value"])
    for k, v in cert.items():
        w.writerow(["certificate", k, csv_safe(v)])
    for k in ("framework", "title", "generated_at", "status", "disclaimer"):
        w.writerow(["dossier", k, csv_safe(dossier[k])])
    for f in dossier["findings"]:
        w.writerow(["findings", "finding", csv_safe(f)])
    for path, v in _flatten(dossier["ledger"]):
        w.writerow(["ledger", path, csv_safe(v)])
    for s in dossier["sections"]:
        for path, v in _flatten(s["data"]):
            w.writerow([s["id"], path, csv_safe(v)])
    return buf.getvalue().encode("utf-8")


def _text_lines(dossier: dict[str, Any], cert: dict[str, Any]) -> list[tuple[str, str]]:
    """(style, text) lines; style is 'h1', 'h2' or 'body'."""
    out = [("h1", "DreamGuard Regulatory Compliance Dossier"), ("h2", dossier["title"]),
           ("body", f"Generated {dossier['generated_at']} by {dossier['generated_by']['username']} ({dossier['generated_by']['role']})"),
           ("body", f"Status: {dossier['status']}")]
    out += [("body", f"  ! {f}") for f in dossier["findings"]]
    out += [("h2", "Cryptographic certificate")] + [("body", f"{k}: {v}") for k, v in cert.items()]
    out += [("body", "The SHA-256 covers the canonical JSON of this dossier (generate with format=json to obtain it).")]
    out += [("h2", "Audit ledger")] + [("body", f"{p}: {v}") for p, v in _flatten(dossier["ledger"])]
    for s in dossier["sections"]:
        out += [("h2", s["title"]), ("body", f"Reference: {s['reference']}")]
        out += [("body", f"{p}: {v}") for p, v in _flatten(s["data"])]
    out += [("h2", "Disclaimer"), ("body", dossier["disclaimer"])]
    return out


def to_pdf(dossier: dict[str, Any], cert: dict[str, Any]) -> bytes:
    """Dependency-free PDF 1.4 writer: text only, A4, built-in Type1 fonts."""
    width, chars, top, bottom, left = 595, 104, 800, 50, 40
    sizes = {"h1": (15, "F2", 22), "h2": (11, "F2", 18), "body": (8, "F1", 10.5)}
    lines: list[tuple[str, str]] = []
    for style, text in _text_lines(dossier, cert):
        limit = chars if style == "body" else 70
        text = text.encode("latin-1", "replace").decode("latin-1")
        lines += [(style, text[i:i + limit]) for i in range(0, max(len(text), 1), limit)]
    pages, cur, y = [], [], top
    for style, text in lines:
        size, font, lead = sizes[style]
        if y - lead < bottom:
            pages.append(cur)
            cur, y = [], top
        y -= lead
        esc = text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
        cur.append(f"BT /{font} {size} Tf {left} {y:.1f} Td ({esc}) Tj ET")
    pages.append(cur)

    objs = ["<< /Type /Catalog /Pages 2 0 R >>", "", "<< /Type /Font /Subtype /Type1 /BaseFont /Courier /Encoding /WinAnsiEncoding >>",
            "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>"]
    kids = []
    for n, body in enumerate(pages, 1):
        body.append(f"BT /F1 7 Tf {left} 30 Td (DreamGuard dossier {cert['dossier_sha256'][:16]}... page {n}/{len(pages)}) Tj ET")
        stream = "\n".join(body).encode("latin-1")
        objs.append(f"<< /Length {len(stream)} >>\nstream\n{stream.decode('latin-1')}\nendstream")
        objs.append(f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {width} 842] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents {len(objs)} 0 R >>")
        kids.append(f"{len(objs)} 0 R")
    objs[1] = f"<< /Type /Pages /Kids [{' '.join(kids)}] /Count {len(kids)} >>"
    out, offsets = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n"), []
    for i, o in enumerate(objs, 1):
        offsets.append(len(out))
        out += f"{i} 0 obj\n{o}\nendobj\n".encode("latin-1")
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode()
    out += "".join(f"{off:010d} 00000 n \n" for off in offsets).encode()
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    return bytes(out)
